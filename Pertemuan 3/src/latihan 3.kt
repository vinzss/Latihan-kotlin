fun main() {
    var saldo = 100000
    println("Saldo awal      : $saldo")

    saldo += 50000
    println("Setelah tambah  : $saldo")

    saldo -= 25000
    println("Setelah kurang  : $saldo")

    saldo *= 2
    println("Setelah kali    : $saldo")

    saldo /= 2
    println("Setelah bagi    : $saldo")
}
